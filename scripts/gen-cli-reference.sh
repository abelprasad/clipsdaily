#!/bin/bash
# Regenerate docs/cli-reference.md from the real CLI help output.
# Requires the package installed (make install). Run via `make docs`.
set -e
cd "$(dirname "$0")/.."
OUT=docs/cli-reference.md
{
  echo "# CLI reference"
  echo
  echo "<!-- Generated by scripts/gen-cli-reference.sh from the real CLI. Do not edit by hand. -->"
  echo
  echo '```'
  clipsdaily --help
  echo '```'
  for cmd in "run" "post" "post now" "post one" "post hourly" "queue" "queue status" "queue maintain" "queue seed" "campaign" "campaign watch" "campaign cut" "submit" "submit scan" "submit list-pending" "submit write-job" "submit mark-submitted" "submit mark-failed" "earnings" "auth"; do
    echo
    echo "## clipsdaily $cmd"
    echo
    echo '```'
    # shellcheck disable=SC2086
    clipsdaily $cmd --help
    echo '```'
  done
} > "$OUT"
echo "wrote $OUT"
